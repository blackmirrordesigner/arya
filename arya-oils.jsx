function OilCard({ oil }) {
  const [open, setOpen] = useOilState(false);
  const [bioOpen, setBioOpen] = useOilState(false);

  const blocks = [
    { h: 'Кому это масло', p: oil.who },
    { h: 'Что изменится и когда', p: oil.change },
    { h: 'Как принимать', p: oil.take, bridge: F_BRIDGE },
    { h: 'Как хранить', p: oil.store },
    { h: 'Дозировка по возрасту и состоянию', p: oil.dose },
    { h: 'Когда не подходит', p: oil.avoid },
  ];

  return (
    <div className="oil-card">
      <button className="oil-head" aria-expanded={open} onClick={() => setOpen((v) => !v)}>
        <span className="onum">{oil.no}</span>
        <span className="omid">
          <span className="oname">{oil.name}</span>
          <span className="oprev">{oil.prev}</span>
          <span className={'ostatus' + (oil.status === 'approved' ? ' approved' : '')}>
            {oil.status === 'approved' ? 'Полный текст — пакетом' : 'Черновик'}
          </span>
        </span>
        <span className="otoggle">{open ? 'Закрыть —' : 'Открыть +'}</span>
      </button>

      {open &&
        <div className="oil-body">
          <div className="oil-inner">
            {blocks.map((b) =>
              <div className="oil-block" key={b.h}>
                <h5>{b.h}</h5>
                <p>{b.p}</p>
                {b.bridge && <div className="bridge-f">{b.bridge}</div>}
              </div>
            )}
            <div className="oil-bio">
              <button className="res-toggle" onClick={() => setBioOpen((v) => !v)}>
                {bioOpen ? 'Скрыть состав ▴' : 'Подробнее о составе ▾'}
              </button>
              {bioOpen &&
                <div className="oil-bio-body">
                  {oil.bio.draft ?
                    <span className="ph">{oil.bio.text}</span> :
                    <span>{oil.bio.text}</span>}
                </div>
              }
            </div>
          </div>
        </div>
      }
    </div>);

}

